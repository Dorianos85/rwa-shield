/** Generate static website examples from the canonical model, without network I/O. */
import { writeFile } from 'node:fs/promises';
import { computeEcv } from '../src/ecv/model.mjs';
import { DEFAULT_PARAMS } from '../src/ecv/params.mjs';
import { generateSeries } from '../src/data/prices.mjs';
import { runBacktest } from '../src/backtest/engine.mjs';
import { SCENARIOS } from '../src/backtest/scenarios.mjs';

const input = {
  mint: 'SPYx', symbol: 'SPYx', qty: 1000, oraclePrice: 100,
  twapPrice: 100, priceAgeSec: 4, impactPct: 1, routableUsd: 150000,
  sessionState: 'regular', realizedVolAnnual: DEFAULT_PARAMS.volRefAnnual,
  routeLabel: 'synthetic:illustration'
};
const cases = {
  fresh: input,
  stale: { ...input, priceAgeSec: DEFAULT_PARAMS.maxStalenessSec + 1 },
  thin: { ...input, routableUsd: DEFAULT_PARAMS.depthFloorUsd - 1 }
};
const scenarios = Object.fromEntries(Object.entries(cases).map(([key, value]) =>
  [key, { input: value, result: computeEcv(value) }]));
const series = generateSeries();
const validation = SCENARIOS.map(scenario => ({
  id: scenario.id,
  ...runBacktest(scenario.transform(series), {
    params: DEFAULT_PARAMS, depthStressFactor: scenario.depthStressFactor,
    label: scenario.id
  })
}));
const data = {
  source: 'src/ecv/model.mjs + DEFAULT_PARAMS; synthetic examples, not market quotes',
  thresholds: { maxStalenessSec: DEFAULT_PARAMS.maxStalenessSec, depthFloorUsd: DEFAULT_PARAMS.depthFloorUsd },
  scenarios, validation
};
await writeFile(new URL('../docs/demo-data.js', import.meta.url),
  '// Generated by scripts/build-website-demo.mjs. Do not edit manually.\n' +
  'window.RWA_DEMO = ' + JSON.stringify(data, null, 2) + ';\n');
